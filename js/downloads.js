/* ============================================================
   downloads.js — PDF download list page (downloads.html)
   ------------------------------------------------------------
   WHAT THIS FILE DOES (plain-English summary for reviewers):
   1. Fetches the paper catalog — papers/feed.json if present
      (regenerated by build.py), falling back to js/papers-data.json.
   2. Renders ONE ROW PER PAPER into #download-rows. Each row is a
      compact list item whose primary action is a raw link straight
      to the PDF file (downloads/<id>.pdf). No intermediate pages,
      no dialogs — clicking "PDF" starts the download.
   3. Wires up the search box and category filter buttons so only
      matching rows stay visible.
   4. Supports deep links like downloads.html?q=privacy (pre-fills
      the search box) so other sites can link into a filtered view.

   This page never needs editing when a paper is added — the JSON
   catalog drives everything. See README.md for the publishing flow.
   ============================================================ */

(function () {
  "use strict";

  // ---- 1. Load the paper list -------------------------------------------
  function loadCatalog() {
    return fetch("papers/feed.json", { cache: "no-store" })
      .then(function (res) { if (!res.ok) throw new Error("no feed"); return res.json(); })
      .catch(function () { return fetch("js/papers-data.json").then(function (r) {
        if (!r.ok) throw new Error("Could not load the paper catalog (HTTP " + r.status + ")");
        return r.json();
      }); });
  }

  loadCatalog()
    .then(function (data) {
      var papers = (data.papers || []).filter(function (p) {
        return p && (p.id || p.slug) && !/^(draft|soon)$/i.test(p.status || "live");
      }).map(function (p) {
        // Normalize the two catalog shapes into one: feed.json uses
        // slug/description, papers-data.json uses id/summary.
        return {
          id: p.id || p.slug,
          summary: p.summary || p.description || "",
          title: p.title, authors: p.authors, category: p.category,
          keywords: p.keywords || [], date: p.date, version: p.version,
          pages: p.pages, number: p.number, pdfUrl: p.pdfUrl,
          readUrl: p.readUrl, mdUrl: p.mdUrl, status: p.status
        };
      });
      // Newest first, using the ISO date string (safe lexicographic sort).
      papers.sort(function (a, b) { return String(b.date).localeCompare(String(a.date)); });
      renderRows(papers);
      wireFilters(papers);
    })
    .catch(function (err) { showError(err.message); });

  // ---- 2. Render one compact row per paper -------------------------------
  function renderRows(papers) {
    var list = document.getElementById("download-rows");
    if (!list) return;

    var html = "";
    papers.forEach(function (p) {
      var authors = (p.authors && p.authors.length) ? p.authors.join(", ") : "IEP Research Division";
      var ident = identifier(p);
      var sizeHint = p.pages ? esc(String(p.pages)) + " pp." : "";
      html +=
        '<li class="dl-row" data-category="' + esc(p.category) + '" ' +
        'data-search="' + esc((p.title + " " + p.summary + " " + authors + " " + p.keywords.join(" ") + " " + ident).toLowerCase()) + '">' +
          '<div class="dl-row__icon"><i class="fas fa-file-pdf"></i></div>' +
          '<div class="dl-row__main">' +
            '<a class="dl-row__title" href="' + esc(p.pdfUrl) + '" download>' + esc(p.title) + '</a>' +
            '<p class="dl-row__byline">' + esc(ident) + ' · ' + esc(authors) + '</p>' +
          '</div>' +
          '<div class="dl-row__meta">' +
            '<span>' + esc(p.category) + '</span>' +
            '<span>' + esc(p.date) + '</span>' +
            (sizeHint ? '<span>' + sizeHint + '</span>' : '') +
          '</div>' +
          '<div class="dl-row__actions">' +
            '<a class="btn btn--primary btn--sm" href="' + esc(p.pdfUrl) + '" download><i class="fas fa-file-arrow-down"></i> PDF</a>' +
            '<a class="btn btn--ghost btn--sm" href="' + esc(p.readUrl) + '" title="Read in browser">HTML</a>' +
          '</div>' +
        '</li>';
    });
    list.innerHTML = html;
    // Rows are NOT given class="reveal": they must be visible immediately
    // even if IntersectionObserver never fires (this was a past bug).
  }

  // Same arXiv-style identifier logic as the About page (IEP-2026.0001).
  // Kept identical on purpose so both pages show the same number for a paper.
  function identifier(p) {
    var num = (p.number || "").replace(/\D+/g, "");
    if (!num) {
      var h = 0, s = String(p.id || p.slug || "x");
      for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 9000;
      num = String(1000 + h);
    }
    while (num.length < 4) num = "0" + num;
    var year = String(p.date || "").slice(0, 4) || "2026";
    return "IEP-" + year + "." + num;
  }

  // ---- 3. Search + category filters --------------------------------------
  function wireFilters(papers) {
    var searchBox = document.getElementById("paper-search");
    var filterWrap = document.getElementById("category-filters");
    var countEl = document.getElementById("result-count");
    var activeCategory = "all";

    if (filterWrap) {
      var cats = ["all"];
      papers.forEach(function (p) { if (cats.indexOf(p.category) === -1) cats.push(p.category); });
      filterWrap.innerHTML = cats.map(function (c, i) {
        return '<button class="filter-btn' + (i === 0 ? " is-active" : "") + '" data-cat="' + esc(c) + '">' +
               esc(cap(c)) + "</button>";
      }).join("");
      filterWrap.addEventListener("click", function (e) {
        var btn = e.target.closest(".filter-btn");
        if (!btn) return;
        activeCategory = btn.dataset.cat;
        filterWrap.querySelectorAll(".filter-btn").forEach(function (b) { b.classList.remove("is-active"); });
        btn.classList.add("is-active");
        applyFilters();
      });
    }

    if (searchBox) {
      searchBox.addEventListener("input", applyFilters);
      var params = new URLSearchParams(window.location.search);
      if (params.get("q")) { searchBox.value = params.get("q"); applyFilters(); }
    }

    function applyFilters() {
      var q = (searchBox && searchBox.value.trim().toLowerCase()) || "";
      var visible = 0;
      document.querySelectorAll("#download-rows .dl-row").forEach(function (row) {
        var catOk = activeCategory === "all" || row.dataset.category === activeCategory;
        var textOk = !q || row.dataset.search.indexOf(q) !== -1;
        var show = catOk && textOk;
        row.hidden = !show;
        if (show) visible++;
      });
      if (countEl) countEl.textContent = visible === 1 ? "1 paper" : visible + " papers";
      var empty = document.getElementById("no-results");
      if (empty) empty.hidden = visible !== 0;
    }
  }

  // ---- helpers -------------------------------------------------------------
  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }
  function cap(s) { return s.charAt(0).toUpperCase() + s.slice(1); }
  function showError(msg) {
    var list = document.getElementById("download-rows");
    if (list) {
      list.innerHTML = '<p class="load-error"><strong>The download list failed to load.</strong> ' +
        esc(msg) + "</p>";
    }
  }
})();
