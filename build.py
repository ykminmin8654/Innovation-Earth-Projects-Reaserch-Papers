#!/usr/bin/env python3
"""
build.py - OPTIONAL helper that mirrors papers/*.pdf into downloads/.

THE SITE IS AUTOMATIC. The download list at /downloads/ reads the
papers/ folder directly from GitHub when a visitor loads the page
(see js/catalog.js). You never need this script to publish a paper:
just upload  papers/<name>.pdf  on GitHub and it appears.

This script exists only for one convenience: keeping a duplicate of
every PDF under downloads/ so short, stable links like
/downloads/<name>.pdf keep working for anyone who bookmarked or cited
them. It does exactly three things:
  1. Copies every papers/*.pdf  ->  downloads/<same name>.pdf
  2. Rebuilds downloads/all-papers.zip with those PDFs
  3. Writes papers/feed.json — a static snapshot catalog used ONLY as
     the offline fallback if the GitHub API can't be reached.

It creates NO markdown files, NO HTML pages, and NEVER modifies your
PDFs (byte-for-byte copies). Safe to run any time; safe to ignore.

Usage:
    python3 build.py          # mirror PDFs + rebuild zip + feed.json
    python3 build.py --clean  # also delete stale copies in downloads/
"""
import json, os, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
PAPERS_DIR = os.path.join(ROOT, "papers")
DOWNLOADS_DIR = os.path.join(ROOT, "downloads")

def main():
    pdfs = sorted(f for f in os.listdir(PAPERS_DIR) if f.lower().endswith(".pdf"))
    if not pdfs:
        print("No PDFs found in papers/ — nothing to do.")
        return

    os.makedirs(DOWNLOADS_DIR, exist_ok=True)

    # 1. Mirror each PDF into downloads/ (verbatim copies).
    entries = []
    for name in pdfs:
        src = os.path.join(PAPERS_DIR, name)
        dst = os.path.join(DOWNLOADS_DIR, name)
        shutil.copy2(src, dst)
        size = os.path.getsize(src)
        slug = name[:-4]
        title = slug.replace("-", " ").replace("_", " ").strip().title()
        entries.append({
            "slug": slug,
            "title": title,
            "pdfUrl": "papers/" + name,          # canonical: the uploaded file
            "mirrorUrl": "downloads/" + name,    # stable short link
            "sizeKb": round(size / 1024),
        })
        print(f"  copied {name} ({size} bytes)")

    # 2. One zip bundle of everything.
    zip_path = os.path.join(DOWNLOADS_DIR, "all-papers.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in pdfs:
            zf.write(os.path.join(PAPERS_DIR, name), arcname=name)
    print(f"  wrote {zip_path}")

    # 3. Static fallback catalog (the live list comes from GitHub itself).
    feed = {
        "$comment": "STATIC SNAPSHOT fallback only. The live download list is generated by js/catalog.js reading the papers/ folder via the GitHub API. Regenerate this file with `python3 build.py` if you want the offline fallback refreshed.",
        "site": "https://researchpapers.innovationearthprojects.org/",
        "generatedAt": "auto",
        "papers": entries,
    }
    with open(os.path.join(PAPERS_DIR, "feed.json"), "w") as fh:
        json.dump(feed, fh, indent=2)
    print("  wrote papers/feed.json (fallback snapshot)")

    if "--clean" in sys.argv:
        # Only ever remove stale *PDF* copies — index.html, zip, etc. stay.
        keep = set(pdfs) | {"all-papers.zip"}
        for f in [x for x in os.listdir(DOWNLOADS_DIR) if x.lower().endswith(".pdf")]:
            if f not in keep:
                os.remove(os.path.join(DOWNLOADS_DIR, f))
                print(f"  cleaned stale downloads/{f}")


if __name__ == "__main__":
    main()
